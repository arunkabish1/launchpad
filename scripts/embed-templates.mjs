import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const TEMPLATES_ROOT = path.join(ROOT, "templates");
const OUT = path.join(ROOT, "lib", "template-assets.gen.ts");
const META_FILE = "template.json";
const SPECIAL_DIRS = new Set(["_provision", "_preview"]);
const SKIP_ARTIFACTS = new Set([
  "node_modules",
  ".wrangler",
  ".dev.vars",
  "venv",
  ".venv",
  "__pycache__",
  ".next",
  "dist",
  "coverage",
]);

function walk(dir, prefix) {
  const out = [];
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    if (entry.name === META_FILE) continue;
    if (SKIP_ARTIFACTS.has(entry.name)) continue;
    const full = path.join(dir, entry.name);
    const rel = prefix ? `${prefix}/${entry.name}` : entry.name;
    if (entry.isDirectory()) {
      out.push(...walk(full, rel));
    } else {
      out.push(rel);
    }
  }
  return out.sort();
}

const assets = {};
const meta = {};

for (const entry of fs.readdirSync(TEMPLATES_ROOT, { withFileTypes: true })) {
  if (!entry.isDirectory()) continue;
  if (SPECIAL_DIRS.has(entry.name)) continue;
  const dir = path.join(TEMPLATES_ROOT, entry.name);
  const metaPath = path.join(dir, META_FILE);
  if (!fs.existsSync(metaPath)) continue;
  meta[entry.name] = JSON.parse(fs.readFileSync(metaPath, "utf8"));
  for (const rel of walk(dir, "")) {
    const full = path.join(dir, rel);
    const data = fs.readFileSync(full);
    assets[`${entry.name}/${rel}`] = data.toString("base64");
  }
}

const provisionPath = path.join(TEMPLATES_ROOT, "_provision", "provision.mjs");
const previewPath = path.join(TEMPLATES_ROOT, "_preview", "preview.mjs");
const provision = fs.readFileSync(provisionPath, "utf8");
const preview = fs.readFileSync(previewPath, "utf8");

function emitMap(obj) {
  return `{\n${Object.entries(obj)
    .map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`)
    .join("\n")}\n}`;
}

const body = `// AUTO-GENERATED by scripts/embed-templates.mjs — do not edit.
// Regenerate with: node scripts/embed-templates.mjs

export const TEMPLATE_ASSETS: Record<string, string> = ${emitMap(assets)};

export const TEMPLATE_META: Record<string, unknown> = ${emitMap(meta)};

export const PROVISION_SCRIPT: string = ${JSON.stringify(provision)};

export const PREVIEW_SCRIPT: string = ${JSON.stringify(preview)};
`;

fs.writeFileSync(OUT, body);
const totalKb = Math.round(Buffer.byteLength(body) / 1024);
console.log(`Wrote ${OUT} (${Object.keys(assets).length} files, ${Object.keys(meta).length} templates, ${totalKb} KB)`);
